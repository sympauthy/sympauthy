package com.sympauthy.business.model.user.claim

import com.sympauthy.util.PublishedUnderAnotherName

/**
 * A claim configured on this authorization server.
 *
 * A claim has two shapes: an [EnabledClaim] this server serves, and a [DisabledClaim] the deployment
 * turned off. A disabled one is listed by the administration API and nothing else: it is unknown to
 * every exchange, so it can neither be collected, written, read, nor published anywhere.
 *
 * Claims can originate from the OpenID Connect specification ([ClaimOrigin.OPENID_CONNECT]) or be
 * custom claims defined by the operator ([ClaimOrigin.CUSTOM]). Access control is determined by the
 * [acl] and the [kind] rather than the claim origin.
 *
 * Equality is based solely on the [id], so that claims can be compared and stored in sets regardless
 * of their type.
 */
sealed class Claim(
    /**
     * Identifier of the claim.
     */
    val id: String,
    /**
     * Identifier of the claim indicating the value of this claims has been verified by the authorization server.
     * Ex. email_verified for the standard email claim.
     */
    val verifiedId: String?,
    /**
     * Type of the claim.
     */
    val dataType: ClaimDataType,
    /**
     * Optional group this claim belongs to (ex. identity, address).
     * Groups are used to organize claims when presenting them to the end-user during authentication flows.
     */
    val group: ClaimGroup?,
    /**
     * True if the end-user MUST provide a value for this claim before completing any authentication flow
     * (either password or third-party providers).
     */
    val required: Boolean,
    /**
     * List of values that are allowed.
     * If null, all values are accepted by this authorization server.
     */
    val allowedValues: List<Any>?,
    /**
     * Identifier of the audience this claim is restricted to.
     * When null, the claim is shared across all audiences.
     */
    val audienceId: String?,
    /**
     * Access control list determining who can read/write this claim and under what conditions.
     *
     * A disabled claim carries it too, because turning a claim off does not change what it would be; the
     * permissions read from it are asked of an [EnabledClaim] alone.
     */
    val acl: ClaimAcl
) {

    /**
     * Whose this claim's value is, or null where it is nobody's to write because this server computes
     * it — which is a [GeneratedClaim] and only one.
     *
     * The [acl] is held to it at startup rather than at request time: a personal claim restricted to
     * no audience grants no client write, and an application claim grants neither of the person's.
     */
    abstract val kind: ClaimKind?

    /**
     * Whether the claim value is generated by the authorization server (e.g. `sub`, `updated_at`).
     */
    val generated: Boolean get() = this is GeneratedClaim

    /**
     * Origin of this claim, derived from whether the [id] matches a known OpenID Connect claim.
     */
    val origin: ClaimOrigin
        get() = if (id in OpenIdConnectClaimId.ALL) ClaimOrigin.OPENID_CONNECT else ClaimOrigin.CUSTOM

    /**
     * Return true if a door of this claim opens on consent to the given [scope].
     */
    fun belongsToScope(scope: String): Boolean = scope in acl.consentedScopes

    /**
     * Return true if this claim is one the audience identified by [audienceId] has: either it is restricted to
     * no audience, or it is restricted to that one.
     *
     * This is the whole of the [audienceId] restriction, and it is asked apart from the ACL rather than inside
     * it: what an audience has is a different question from what a caller may read, and a claim may have to be
     * tested for the first where no scope applies — the set of required claims a flow computes is one.
     */
    fun belongsToAudience(audienceId: String): Boolean =
        this.audienceId == null || this.audienceId == audienceId

    /**
     * Return true if this claim is published in [place].
     *
     * This narrows and never grants, so a caller asks it beside the permission test rather than instead
     * of one: a claim the ACL refuses is published in no place whatever this says.
     */
    abstract fun isPublishedIn(place: ClaimPublicationPlace): Boolean

    /**
     * Return true if this claim opens [place] to a request.
     *
     * It says that a request *could* reach [place] and never that one did, so
     * [EnabledClaim.isPublishedIn] taking the request is what decides whether a value is carried; a
     * caller publishing what a claim declares rather than carrying a value asks this instead.
     */
    abstract fun isPublishedInWhenRequested(place: ClaimPublicationPlace): Boolean

    override fun equals(other: Any?) = other is Claim && id == other.id
    override fun hashCode() = id.hashCode()
    override fun toString() = id
}

/**
 * A claim this authorization server serves.
 *
 * Everything a claim can take part in — a collection in the flow, a write through an API, a read, a
 * token — takes one of these rather than a [Claim], which is what keeps a claim the deployment turned
 * off out of an exchange without anything having to test for it.
 *
 * The three subclasses are the three answers to whose its value is:
 * - [PersonalClaim]: the person's ([ClaimKind.PERSONAL]).
 * - [ApplicationClaim]: an application's, attached to the person ([ClaimKind.APPLICATION]).
 * - [GeneratedClaim]: nobody's, because this server computes it.
 */
sealed class EnabledClaim(
    id: String,
    verifiedId: String?,
    dataType: ClaimDataType,
    group: ClaimGroup?,
    required: Boolean,
    allowedValues: List<Any>?,
    audienceId: String?,
    /**
     * The places this claim is published in.
     *
     * Publication is not permission: these narrow what [acl] already allows, and a claim naming no place
     * is still read through the client, admin and user APIs, which the ACL alone gates.
     */
    val publishedIn: Set<ClaimPublicationPlace>,
    /**
     * The places this claim is published in only when a client asks for it by name, through the `claims`
     * request parameter of OpenID Connect Core §5.5.
     *
     * It is the deployment opening a door rather than the client forcing one: a channel named here carries
     * the value for the requests that ask and for no others, and a request naming a claim no channel was
     * opened for adds nothing. A channel named here and in [publishedIn] is refused at startup — always
     * and on-request are two answers for one channel.
     */
    val publishedInWhenRequested: Set<ClaimPublicationPlace>,
    acl: ClaimAcl
) : Claim(id, verifiedId, dataType, group, required, allowedValues, audienceId, acl) {

    /**
     * Should the claim be collected from end-user input during authenticated flow or its value is managed
     * by another mean (generated by server, managed by a client through API, etc.)?
     *
     * Derived from: `!generated` and the [ClaimAcl.collectedInFlow] door not shut, which says the flow
     * could collect it and never that it does for a given person — `ClaimAclManager` answers that.
     */
    val collectedInFlow: Boolean get() = !generated && acl.collectedInFlow != null

    override fun isPublishedIn(place: ClaimPublicationPlace): Boolean = place in publishedIn

    /**
     * Return true if this claim is published in [place] for a grant whose `claims` request parameter named
     * what [requestedClaims] holds: either the deployment publishes it there for every request, or it
     * opened that channel to a request and this request named the claim.
     *
     * This narrows and never grants, exactly as the one-argument [isPublishedIn] does, so a caller asks it
     * beside the permission test rather than instead of one. The request is the last of the questions and
     * the least of them: it cannot reach a claim the ACL refuses, one of another audience, or a channel
     * [publishedInWhenRequested] does not name — see [RequestedClaims].
     */
    fun isPublishedIn(place: ClaimPublicationPlace, requestedClaims: RequestedClaims): Boolean =
        isPublishedIn(place) || (isPublishedInWhenRequested(place) && id in requestedClaims.namesIn(place))

    override fun isPublishedInWhenRequested(place: ClaimPublicationPlace): Boolean =
        place in publishedInWhenRequested
}

/**
 * A claim whose value is the person's: a name, an address, a birth date.
 *
 * Collected from them in the flow or set through their own access token, and never written by a client
 * except where the claim is restricted to that client's own audience.
 */
class PersonalClaim(
    id: String,
    verifiedId: String?,
    dataType: ClaimDataType,
    group: ClaimGroup?,
    required: Boolean,
    allowedValues: List<Any>?,
    audienceId: String? = null,
    publishedIn: Set<ClaimPublicationPlace>,
    publishedInWhenRequested: Set<ClaimPublicationPlace>,
    acl: ClaimAcl
) : EnabledClaim(
    id, verifiedId, dataType, group, required, allowedValues, audienceId, publishedIn, publishedInWhenRequested, acl
) {
    override val kind: ClaimKind get() = ClaimKind.PERSONAL
}

/**
 * A claim whose value is an application's, attached to the person: a credit score, a tier, a flag a
 * backend computes.
 *
 * Read and written through the client scopes its ACL names, and never typed by the person.
 */
class ApplicationClaim(
    id: String,
    verifiedId: String?,
    dataType: ClaimDataType,
    group: ClaimGroup?,
    required: Boolean,
    allowedValues: List<Any>?,
    audienceId: String? = null,
    publishedIn: Set<ClaimPublicationPlace>,
    publishedInWhenRequested: Set<ClaimPublicationPlace>,
    acl: ClaimAcl
) : EnabledClaim(
    id, verifiedId, dataType, group, required, allowedValues, audienceId, publishedIn, publishedInWhenRequested, acl
) {
    override val kind: ClaimKind get() = ClaimKind.APPLICATION
}

/**
 * A claim whose value this authorization server computes (e.g. `sub`, `updated_at`).
 *
 * It is of neither kind, required of nobody, restricted to no audience and opened to no request, and
 * none of that is a deployment's to decide: no key of `claims.<id>` is accepted for one, and it is never
 * turned off.
 */
class GeneratedClaim(
    id: String,
    verifiedId: String?,
    dataType: ClaimDataType,
    group: ClaimGroup?,
    publishedIn: Set<ClaimPublicationPlace>,
    acl: ClaimAcl
) : EnabledClaim(
    id = id,
    verifiedId = verifiedId,
    dataType = dataType,
    group = group,
    required = false,
    allowedValues = null,
    audienceId = null,
    publishedIn = publishedIn,
    publishedInWhenRequested = emptySet(),
    acl = acl
) {
    override val kind: ClaimKind? get() = null
}

/**
 * A claim the deployment turned off, which this server lists and never serves.
 *
 * It carries no reason for being off: there is exactly one, that the deployment wrote `enabled: false`
 * against it, or left a claim the specification defines at the `enabled: false` it ships with.
 *
 * It is published nowhere either, whatever its file names: every place a claim is published in carries
 * or advertises a value, and a disabled claim has none to give.
 *
 * Its [kind] is never null, because a [GeneratedClaim] is never turned off.
 */
class DisabledClaim(
    id: String,
    verifiedId: String?,
    dataType: ClaimDataType,
    override val kind: ClaimKind,
    group: ClaimGroup?,
    required: Boolean,
    allowedValues: List<Any>?,
    audienceId: String? = null,
    acl: ClaimAcl
) : Claim(id, verifiedId, dataType, group, required, allowedValues, audienceId, acl) {
    override fun isPublishedIn(place: ClaimPublicationPlace): Boolean = false

    override fun isPublishedInWhenRequested(place: ClaimPublicationPlace): Boolean = false
}

/**
 * True if this authorization server serves this claim.
 */
val Claim.isEnabled: Boolean get() = this is EnabledClaim

enum class ClaimOrigin(
    override val publishedName: String? = null
) : PublishedUnderAnotherName {
    /**
     * Published as `openid`, the word the OpenID Connect specification uses for the claims it
     * defines, rather than the `openid_connect` this value's name spells.
     */
    OPENID_CONNECT("openid"),
    CUSTOM
}
