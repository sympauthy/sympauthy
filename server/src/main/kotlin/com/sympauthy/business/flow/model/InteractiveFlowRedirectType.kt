package com.sympauthy.business.flow.model

/**
 * How the end-user must be handed back to the flow's initiator once an [InteractiveFlowSession] reaches a
 * terminal status.
 *
 * This tags the [InteractiveFlowHandBack] carried on the session so the transport can build the final redirect
 * without knowing which purpose initiated the session.
 */
enum class InteractiveFlowRedirectType {
    /**
     * OAuth2 authorization-code style: on completion, append the authorization code the session completed
     * with (and the client's echoed `state`) to the redirect URI; once the end-user leaves the flow, return the
     * OAuth2 error answering how it ended there (no code).
     *
     * The code is generated by the session's completion, not by building this redirect, which only reads it.
     */
    AUTHORIZATION_CODE,

    /**
     * Return to a page of the client: the end-user is sent to the return URI with parameters naming the
     * flow, how it ended when it did not complete, and the `return_state` the start request carried.
     */
    PLAIN,
}
